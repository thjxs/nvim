-- Use spaces instead of literal tab characters when pressing Tab.
vim.o.expandtab = true

-- Display a tab character as four columns wide.
vim.o.tabstop = 4

-- Indent by four spaces for autoindent and >>/<< commands.
vim.o.shiftwidth = 4

-- Insert or remove four spaces when pressing Tab or Backspace.
vim.o.softtabstop = 4
